from tensorflow.keras import models
from tensorflow.keras.optimizers import Adam


def create_cnn(
    dropout_rate=0.50,
    learning_rate=0.001
):

    model = models.Sequential([

        layers.Input(
            shape=(128, 128, 1)
        ),

        layers.Conv2D(
            32,
            (3, 3),
            activation="relu"
        ),

        layers.MaxPooling2D(
            (2, 2)
        ),

        layers.Conv2D(
            64,
            (3, 3),
            activation="relu"
        ),

        layers.MaxPooling2D(
            (2, 2)
        ),

        layers.Conv2D(
            128,
            (3, 3),
            activation="relu"
        ),

        layers.MaxPooling2D(
            (2, 2)
        ),

        layers.Flatten(),

        layers.Dense(
            128,
            activation="relu"
        ),

        layers.Dropout(
            dropout_rate
        ),

        layers.Dense(
            1,
            activation="sigmoid"
        )
    ])


    optimizer = Adam(
        learning_rate=learning_rate
    )


    model.compile(

        optimizer=optimizer,

        loss="binary_crossentropy",

        metrics=["accuracy"]
    )


    return model

